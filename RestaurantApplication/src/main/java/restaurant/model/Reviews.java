package restaurant.model;

import java.sql.Timestamp;


public class Reviews {
	protected int reviewId;
	protected double rating;
	protected String writtenReview;
	protected Timestamp created;
	protected Users user;
	protected Restaurants restaurant;
	
	// This constructor can be used for reading records from MySQL, where we have all fields,
	// including the ReviewId.
	public Reviews(int reviewId, double rating, String writtenReview, Timestamp created,
			Users user, Restaurants restaurant) {
		this.reviewId = reviewId;
		this.rating = rating;
		this.writtenReview = writtenReview;
		this.created = created;
		this.user = user;
		this.restaurant = restaurant;
	}
	
	// This constructor can be used for reading records from MySQL, where we only have the reviewId,
	// such as a foreign key reference to ReviewId.
	// Given ReviewId, we can fetch the full Review record.
	public Reviews(int reviewId) {
		this.reviewId = reviewId;
	}
	
	// This constructor can be used for creating new records, where the reviewId may not be
	// assigned yet since it is auto-generated by MySQL.
	public Reviews(double rating, String writtenReview, Timestamp created,
			Users user, Restaurants restaurant) {
		this.rating = rating;
		this.writtenReview = writtenReview;
		this.created = created;
		this.user = user;
		this.restaurant = restaurant;
	}

	public int getReviewId() {
		return reviewId;
	}

	public void setReviewId(int reviewId) {
		this.reviewId = reviewId;
	}

	public double getRating() {
		return rating;
	}

	public void setRating(double rating) {
		this.rating = rating;
	}

	public String getWrittenReview() {
		return writtenReview;
	}

	public void setWrittenReview(String writtenReview) {
		this.writtenReview = writtenReview;
	}

	public Timestamp getCreated() {
		return created;
	}

	public void setCreated(Timestamp created) {
		this.created = created;
	}

	public Users getUser() {
		return user;
	}

	public void setUser(Users user) {
		this.user = user;
	}
	
	public Restaurants getRestaurant() {
		return restaurant;
	}

	public void setRestaurant(Restaurants restaurant) {
		this.restaurant = restaurant;
	}
}